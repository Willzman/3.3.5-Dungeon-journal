"""Build boss portraits for the 3.3.5a client from Encounter Journal art.

Input: portraits.json (boss name -> PNG path, or {A, H} per faction) made by matching
boss names against Gethe/wow-ui-textures, and a checkout of that repository.
Output: DungeonJournal/Media/Bosses/*.tga (32-bit TGA, which 3.3.5a can load) and
DungeonJournal/Data/Portraits.lua.
"""
import json, os, re, sys
from PIL import Image

mapping = json.load(open(sys.argv[1], encoding='utf-8'))
tex_root, addon = sys.argv[2], sys.argv[3]
out_dir = os.path.join(addon, 'Media', 'Bosses')
os.makedirs(out_dir, exist_ok=True)


def convert(png):
    slug = re.sub(r'[^a-z0-9]+', '', os.path.basename(png)[len('UI-EJ-BOSS-'):-4].lower())
    im = Image.open(os.path.join(tex_root, png)).convert('RGBA')
    if im.size != (128, 64):
        im = im.resize((128, 64), Image.LANCZOS)
    im.save(os.path.join(out_dir, slug + '.tga'))
    return slug


def lua_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


lines = ['-- Generated by tools/portraits.py: boss name -> Media/Bosses/<file>.tga',
         '-- (Encounter Journal portraits; per faction where the encounter differs).',
         'local DJ = DungeonJournal', 'DJ.Portraits = {']
for name in sorted(mapping):
    v = mapping[name]
    if isinstance(v, dict):
        lines.append('    [%s] = { A = %s, H = %s },' % (lua_str(name), lua_str(convert(v['A'])), lua_str(convert(v['H']))))
    else:
        lines.append('    [%s] = %s,' % (lua_str(name), lua_str(convert(v))))
lines.append('}')
open(os.path.join(addon, 'Data', 'Portraits.lua'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print(len(mapping), 'bosses,', len(os.listdir(out_dir)), 'portrait files')

def _naxx(base, extra=None):
    keys10 = extra or [base]
    return {'R10': keys10, 'R25': [k + '25Man' for k in keys10]}


def _voa(name, pages, faction=False):
    suf = ['_A', '_H'] if faction else ['']
    def keys(sz):
        return [{'A': 'VaultofArchavon%s%d%s_A' % (name, i, sz), 'H': 'VaultofArchavon%s%d%s_H' % (name, i, sz)}
                if faction else 'VaultofArchavon%s%d%s' % (name, i, sz) for i in range(1, pages + 1)]
    return {'R10': keys(''), 'R25': keys('25Man')}


